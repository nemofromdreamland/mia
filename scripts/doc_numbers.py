"""Every number cited by README.md and docs/, computed from files in the repo (task 6.4).

Usage:
    uv run python scripts/doc_numbers.py                       # print the table
    uv run python scripts/doc_numbers.py --write-production  # refresh production_summary.md

Sources: results/*.md (eval metrics), results/production_summary.md (aggregates of the
production run records, which stay out of git because they hold visitor text) and
config/models.yaml (prices).
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path
from typing import Any

PRODUCTION_GLOB = "*_aws-adhoc.jsonl"
SUMMARY_NAME = "production_summary.md"


def md_tables(path: Path) -> dict[str, list[dict[str, str]]]:
    """Parse '## Section' + first markdown table under it into rows keyed by header."""
    tables: dict[str, list[dict[str, str]]] = {}
    section, header = "", None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            section, header = line.lstrip("#").strip(), None
            continue
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            tables.setdefault(section, [])
        elif set("".join(cells)) <= set("-: "):
            continue
        else:
            tables.setdefault(section, []).append(dict(zip(header, cells, strict=False)))
    return tables


def row(table: list[dict[str, str]], **match: str) -> dict[str, str]:
    for candidate in table:
        if all(candidate.get(k) == v for k, v in match.items()):
            return candidate
    raise KeyError(f"no row with {match}")


def _percentile(values: list[float], q: float) -> float:
    ordered = sorted(values)
    k = (len(ordered) - 1) * q
    low = int(k)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (k - low)


def voice_first_audio(records: list[dict[str, Any]]) -> tuple[float, float, int]:
    """(median s, p90 s, n) of time to first audio in voice sessions."""
    values = [
        r["params"]["first_audio_ms"] / 1000
        for r in records
        if r["prompt_name"] == "voice_interviewer" and (r.get("params") or {}).get("first_audio_ms")
    ]
    if not values:
        raise ValueError("no voice_interviewer records with params.first_audio_ms")
    return statistics.median(values), _percentile(values, 0.9), len(values)


def _load(runs_dir: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for path in sorted(runs_dir.glob(PRODUCTION_GLOB)):
        records += [
            json.loads(line)
            for line in path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
    return records


def production_summary(runs_dir: Path) -> str:
    """Aggregates only (counts, cost, tokens, latency): no input or output text."""
    records = _load(runs_dir)
    text = [r for r in records if r["prompt_name"] != "voice_interviewer"]
    voice = [r for r in records if r["prompt_name"] == "voice_interviewer" and r["input_tokens"]]
    reports = sum(1 for r in text if r["prompt_name"] == "report")
    text_cost = sum(r["cost_usd"] or 0 for r in text)
    lat = [r["latency_ms"] for r in text]
    median, p90, n = voice_first_audio(voice) if voice else (0.0, 0.0, 0)
    rows = [
        ("Text calls", f"{len(text)}"),
        ("Text calls with error", f"{sum(1 for r in text if r['error'])}"),
        ("Completed text interviews (report calls)", f"{reports}"),
        ("Text cost, total (USD)", f"{text_cost:.4f}"),
        (
            "Text cost per completed interview, all calls / reports (USD)",
            f"{text_cost / reports:.4f}" if reports else "n/a",
        ),
        (
            "Text call latency p50 / p95 (ms)",
            f"{_percentile(lat, 0.5):.0f} / {_percentile(lat, 0.95):.0f}" if lat else "n/a",
        ),
        ("Voice sessions", f"{len(voice)}"),
        ("Voice time to first audio, median (s)", f"{median:.2f}"),
        ("Voice time to first audio, p90 (s)", f"{p90:.2f}"),
        ("Voice sessions with first-audio measure", f"{n}"),
        ("Voice tokens per session, median (in / out)", _voice_tokens(voice)),
    ]
    body = "\n".join(f"| {k} | {v} |" for k, v in rows)
    return (
        "# Production summary (demo on AWS, 2026-11-17)\n\n"
        "Aggregates of the production run records (`runs/*_aws-adhoc.jsonl`, kept out of git\n"
        "because they hold visitor text). Generated by\n"
        "`uv run python scripts/doc_numbers.py --write-production`.\n\n"
        "| Metric | Value |\n|---|---|\n" + body + "\n"
    )


def _voice_tokens(voice: list[dict[str, Any]]) -> str:
    if not voice:
        return "n/a"
    tin = statistics.median(r["input_tokens"] for r in voice)
    tout = statistics.median(r["output_tokens"] for r in voice)
    return f"{tin:.0f} / {tout:.0f}"


def _numbers(results: Path) -> list[tuple[str, str, str]]:
    base = md_tables(results / "baseline_v1.md")
    jv = md_tables(results / "judge_v1_vs_v2.md")
    rob = md_tables(results / "robustez_v1.md")
    pf = md_tables(results / "promptfoo_set_a.md")
    agree, test = "Concordância juiz × humano", "test (oficial)"
    haiku = "us.anthropic.claude-haiku-4-5-20251001-v1:0"
    v1 = row(jv[agree], Modelo="judge-v1", Split=test)
    v2 = row(jv[agree], Modelo="judge-v2", Split=test)
    out = [
        ("judge v1 kappa (test)", v1["Kappa ponderado (quadrático)"], "results/judge_v1_vs_v2.md"),
        ("judge v2 kappa (test)", v2["Kappa ponderado (quadrático)"], "results/judge_v1_vs_v2.md"),
        ("judge v2 within ±1 (test)", v2["% ±1"], "results/judge_v1_vs_v2.md"),
        ("judge v2 MAE (test)", v2["MAE"], "results/judge_v1_vs_v2.md"),
        (
            "judge n (dev / test)",
            f"{row(jv[agree], Modelo='judge-v2', Split='dev')['n']} / {v2['n']}",
            "results/judge_v1_vs_v2.md",
        ),
    ]
    verb = jv["Viés de verbosidade"]
    out.append(
        (
            "verbosity bias v1 → v2",
            _arrow(verb, _col(verb, "Viés")),
            "results/judge_v1_vs_v2.md",
        )
    )
    cit = jv["Citações verificáveis e itens excluídos"]
    out.append(
        (
            "verifiable quotes v1 → v2",
            _arrow(cit, "Citações verificáveis"),
            "results/judge_v1_vs_v2.md",
        )
    )
    for model in (haiku, "mistral.mistral-large-3-675b-instruct", "us.amazon.nova-pro-v1:0"):
        k = row(base[agree], Modelo=model, Split=test)["Kappa ponderado (quadrático)"]
        out.append((f"baseline kappa (test) {model}", k, "results/baseline_v1.md"))
    setb = base["Conjunto B — decisão de ferramenta (follow_up)"]
    out.append(
        (
            "set B right action, Haiku (all)",
            row(setb, Modelo=haiku, Split="todos")["% ação certa"],
            "results/baseline_v1.md",
        )
    )
    d = rob["Conjunto D — robustez (sem e com Guardrails)"]
    for scenario in ("haiku", "haiku+guardrail"):
        r = row(d, Cenário=scenario, Split="todos")
        out.append(
            (
                f"set D attacks that worked, {scenario} (n={r['n']})",
                r["% funcionou"],
                "results/robustez_v1.md",
            )
        )
    out.append(
        (
            "set D guardrail false positives",
            row(d, Cenário="haiku+guardrail", Split="todos")["Falsos positivos"],
            "results/robustez_v1.md",
        )
    )
    cost = row(pf["Custo e latência"], Prompt="judge")
    out.append(
        (
            "judge cost per call (USD), p50 / p95 ms",
            f"{cost['Custo médio (US$)']}, {cost['p50 (ms)']} / {cost['p95 (ms)']}",
            "results/promptfoo_set_a.md",
        )
    )
    summary = results / SUMMARY_NAME
    if summary.exists():
        for metric in md_tables(summary).get("Production summary (demo on AWS, 2026-11-17)", []):
            out.append((f"prod: {metric['Metric']}", metric["Value"], f"results/{SUMMARY_NAME}"))
    return out


def _arrow(table: list[dict[str, str]], column: str) -> str:
    before = row(table, Modelo="judge-v1")[column]
    after = row(table, Modelo="judge-v2")[column]
    return f"{before} → {after}"


def _col(table: list[dict[str, str]], prefix: str) -> str:
    return next(k for k in table[0] if k.startswith(prefix))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=Path("results"))
    parser.add_argument("--runs", type=Path, default=Path("runs"))
    parser.add_argument("--write-production", action="store_true")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if args.write_production:
        (args.results / SUMMARY_NAME).write_text(
            production_summary(args.runs), encoding="utf-8", newline="\n"
        )
    print("| Number | Value | Source |\n|---|---|---|")
    for name, value, source in _numbers(args.results):
        print(f"| {name} | {value} | `{source}` |")
    return 0


if __name__ == "__main__":
    sys.exit(main())
